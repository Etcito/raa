//! API file discovery: lists `src/api/*.rs` sorted by file name and writes
//! `$OUT_DIR/api_registry.rs` (one `#[path]` module per file plus `install_all` and
//! `frame_all` calling each file's `install` and `frame` in that order) and
//! `$OUT_DIR/api_files.txt` (one stem per line, read by `tests/api_registry.rs`).
//!
//! The generated code names `InstallCtx`, `EngineState`, `GpuContext`, `FrameInput` and
//! `RaaError` unqualified: the `mod api` that includes it brings them into scope.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs, io};

fn main() {
    println!("cargo:rerun-if-changed=src/api");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo::rustc-check-cfg=cfg(raa_js_engine)");

    let manifest =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let out = PathBuf::from(env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let files = match api_files(&manifest.join("src").join("api")) {
        Ok(f) => f,
        Err(e) => panic!("raa-js build.rs: cannot list src/api: {e}"),
    };

    let registry = registry_source(&files);
    let mut list = String::new();
    for (stem, _) in &files {
        list.push_str(stem);
        list.push('\n');
    }
    write(&out.join("api_registry.rs"), &registry);
    write(&out.join("api_files.txt"), &list);
}

fn write(path: &Path, text: &str) {
    if let Err(e) = fs::write(path, text) {
        panic!("raa-js build.rs: cannot write {}: {e}", path.display());
    }
}

/// `(stem, absolute path)` of every `*.rs` file of `dir`, sorted by file name. A missing
/// directory is the empty case.
fn api_files(dir: &Path) -> io::Result<Vec<(String, PathBuf)>> {
    let entries = match fs::read_dir(dir) {
        Ok(e) => e,
        Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(e) => return Err(e),
    };
    let mut files = Vec::new();
    for entry in entries {
        let path = entry?.path();
        if !path.is_file() || path.extension().and_then(|x| x.to_str()) != Some("rs") {
            continue;
        }
        let Some(stem) = path.file_stem().and_then(|s| s.to_str()) else {
            panic!(
                "raa-js build.rs: non UTF-8 api file name {}",
                path.display()
            );
        };
        let valid = stem
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_lowercase() || c == '_')
            && stem
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
        if !valid {
            panic!("raa-js build.rs: api file stem `{stem}` is not a snake_case module name");
        }
        let abs = fs::canonicalize(&path)?;
        files.push((stem.to_string(), abs));
    }
    files.sort_by(|a, b| a.0.cmp(&b.0));
    Ok(files)
}

fn registry_source(files: &[(String, PathBuf)]) -> String {
    let mut s =
        String::from("// @generated by crates/raa-js/build.rs from src/api/*.rs; do not edit.\n\n");
    for (stem, path) in files {
        let Some(p) = path.to_str() else {
            panic!("raa-js build.rs: non UTF-8 path {}", path.display());
        };
        let _ = writeln!(s, "#[path = {p:?}]\nmod {stem};\n");
    }

    s.push_str("/// Calls each api file's `install` in file-name order.\n");
    s.push_str("pub(crate) fn install_all(ctx: &mut InstallCtx<'_>) -> Result<(), RaaError> {\n");
    if files.is_empty() {
        s.push_str("    let _ = ctx;\n");
    }
    for (stem, _) in files {
        let _ = writeln!(s, "    {stem}::install(ctx)?;");
    }
    s.push_str("    Ok(())\n}\n\n");

    s.push_str("/// Calls each api file's `frame` in file-name order.\n");
    s.push_str(
        "pub(crate) fn frame_all(st: &mut EngineState, gpu: &GpuContext, input: &FrameInput) -> Result<(), RaaError> {\n",
    );
    if files.is_empty() {
        s.push_str("    let _ = (st, gpu, input);\n");
    }
    for (stem, _) in files {
        let _ = writeln!(s, "    {stem}::frame(st, gpu, input)?;");
    }
    s.push_str("    Ok(())\n}\n");
    s
}
