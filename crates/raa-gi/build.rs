//! Part-file discovery: lists `src/parts/*.rs` sorted by file name and writes
//! `$OUT_DIR/gi_parts.rs` (one `#[path]` module per file plus `install_parts`, which calls each
//! file's `install` in that order).
//!
//! The generated code names `PartsCtx` and `RaaError` unqualified: `src/parts.rs`, which includes
//! it, brings them into scope.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs, io};

fn main() {
    println!("cargo:rerun-if-changed=src/parts");
    println!("cargo:rerun-if-changed=build.rs");

    let manifest =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let out = PathBuf::from(env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let files = match part_files(&manifest.join("src").join("parts")) {
        Ok(files) => files,
        Err(e) => panic!("raa-gi build.rs: cannot list src/parts: {e}"),
    };

    write(&out.join("gi_parts.rs"), &registry_source(&files));
}

fn write(path: &Path, text: &str) {
    if let Err(e) = fs::write(path, text) {
        panic!("raa-gi build.rs: cannot write {}: {e}", path.display());
    }
}

/// `(stem, absolute path)` of every `*.rs` file of `dir`, sorted by file name. A missing
/// directory is the empty case.
fn part_files(dir: &Path) -> io::Result<Vec<(String, PathBuf)>> {
    let entries = match fs::read_dir(dir) {
        Ok(e) => e,
        Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(e) => return Err(e),
    };
    let mut files = Vec::new();
    for entry in entries {
        let path = entry?.path();
        if !path.is_file() || path.extension().and_then(|x| x.to_str()) != Some("rs") {
            continue;
        }
        let Some(stem) = path.file_stem().and_then(|s| s.to_str()) else {
            panic!(
                "raa-gi build.rs: non UTF-8 part file name {}",
                path.display()
            );
        };
        let valid = stem
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_lowercase() || c == '_')
            && stem
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
        if !valid {
            panic!("raa-gi build.rs: part file stem `{stem}` is not a snake_case module name");
        }
        let abs = fs::canonicalize(&path)?;
        files.push((stem.to_string(), abs));
    }
    files.sort_by(|a, b| a.0.cmp(&b.0));
    Ok(files)
}

fn registry_source(files: &[(String, PathBuf)]) -> String {
    let mut s = String::from(
        "// @generated by crates/raa-gi/build.rs from src/parts/*.rs; do not edit.\n\n",
    );
    for (stem, path) in files {
        let Some(p) = path.to_str() else {
            panic!("raa-gi build.rs: non UTF-8 path {}", path.display());
        };
        let _ = writeln!(s, "#[path = {p:?}]\npub mod {stem};\n");
    }

    s.push_str("pub(crate) fn install_parts(ctx: &mut PartsCtx<'_>) -> Result<(), RaaError> {\n");
    if files.is_empty() {
        s.push_str("    let _ = ctx;\n");
    }
    for (stem, _) in files {
        let _ = writeln!(s, "    {stem}::install(ctx)?;");
    }
    s.push_str("    Ok(())\n}\n");
    s
}
